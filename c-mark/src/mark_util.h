#ifndef MARK_UTIL_H
#define MARK_UTIL_H
#include "cu.h"

/* goldmark's util package (util/util.go) and its two generated tables.
 * Byte classification mirrors goldmark's 256-entry tables; rune
 * classification combines them with Go's unicode package (mark_unicode.h).
 * Indices are long, as Go's ints are, since several callers use negative
 * values as "none". */

/* util.HTML5Entity. chars is the entity's UTF-8, chars_len bytes. */
typedef struct MarkEntity {
    const char *name;
    size_t name_len;
    const char *chars;
    size_t chars_len;
} MarkEntity;

/* One entry of util.unicodeCaseFoldings: from folds to to[0..count). */
typedef struct MarkFolding {
    unsigned long from;
    unsigned long to[3];
    size_t count;
} MarkFolding;

/* mark_entities.c and mark_casefold.c, generated by tools/gen_tables.py. */
const MarkEntity *mark_entity_lookup(CuStr name);
const MarkFolding *mark_folding_lookup(unsigned long c);

/* Go's utf8.RuneError. */
#define MARK_RUNE_ERROR 0xFFFDUL

/* utf8.DecodeRune: the rune at p (n bytes available) and its size in
 * *size. Invalid or truncated input gives MARK_RUNE_ERROR with size 1; an
 * empty input gives MARK_RUNE_ERROR with size 0. */
unsigned long mark_decode_rune(const unsigned char *p, long n, long *size);
/* utf8.RuneStart */
int mark_rune_start(unsigned char c);
/* utf8.EncodeRune into out[4]; an invalid rune encodes as U+FFFD. */
long mark_encode_rune(unsigned char *out, unsigned long r);
/* utf8.ValidRune: not a surrogate, at most U+10FFFF. */
int mark_valid_rune(unsigned long r);
/* util.ToValidRune */
unsigned long mark_to_valid_rune(unsigned long r);
/* util.ToRune: the rune whose encoding covers source[pos]. */
unsigned long mark_to_rune(const unsigned char *source, long len, long pos);

/* util.IsSpace, IsPunct, IsNumeric, IsHexDecimal, IsAlphaNumeric, UTF8Len */
int mark_byte_space(unsigned char c);
int mark_byte_punct(unsigned char c);
int mark_byte_numeric(unsigned char c);
int mark_byte_hex(unsigned char c);
int mark_byte_alnum(unsigned char c);
int mark_utf8_len(unsigned char c);
/* util.IsSpaceRune, IsPunctRune */
int mark_rune_space(unsigned long r);
int mark_rune_punct(unsigned long r);

/* util.IsBlank */
int mark_is_blank(const unsigned char *s, long len);
/* util.TabWidth */
long mark_tab_width(long pos);
/* util.TrimLeftSpaceLength, TrimRightSpaceLength */
long mark_trim_left_space_len(const unsigned char *s, long len);
long mark_trim_right_space_len(const unsigned char *s, long len);
/* util.TrimLeftSpace and util.TrimRightSpace on bytes: unlike IsSpace,
 * their set includes \v and \f. */
CuStr mark_trim_spaces(CuStr s);
/* util.FindURLIndex, util.FindEmailIndex */
long mark_find_url_index(const unsigned char *s, long len);
long mark_find_email_index(const unsigned char *s, long len);
/* util.EscapeHTMLByte: the escape for c, or NULL */
const char *mark_escape_html_byte(unsigned char c);

/* The byte-building functions below append to a CuBuilder; failures are
 * sticky on the builder, as cu.h documents. */

/* util.EscapeHTML */
void mark_escape_html(CuBuilder *b, CuStr s);
/* util.URLEscape */
void mark_url_escape(CuBuilder *b, CuStr s, int resolve_reference);
/* util.ToLinkReference: the normalised key of a link label */
void mark_to_link_reference(CuBuilder *b, CuStr label);

#endif
