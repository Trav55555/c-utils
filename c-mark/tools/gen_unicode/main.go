// Command gen_unicode writes src/mark_unicode.c: the Unicode properties
// goldmark v1.6.0 and Hugo 0.120.4 take from Go's unicode package, as
// sorted range tables, so c-mark classifies every code point as they do.
//
//	cd tools/gen_unicode && go run . > ../../src/mark_unicode.c
//
// The tables follow the Unicode version of the Go that runs this (recorded
// in the output); Hugo 0.120.4 was released with Go 1.21, whose unicode
// package is Unicode 15.0.0, as is Go 1.22's.
package main

import (
	"fmt"
	"os"
	"runtime"
	"unicode"
)

type rng struct{ lo, hi rune }

func ranges(is func(rune) bool) []rng {
	var out []rng
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !is(r) {
			continue
		}
		if n := len(out); n > 0 && out[n-1].hi == r-1 {
			out[n-1].hi = r
		} else {
			out = append(out, rng{r, r})
		}
	}
	return out
}

func table(w *os.File, name, doc string, rs []rng) {
	fmt.Fprintf(w, "/* %s */\nstatic const MarkRange %s[%d] = {\n", doc, name, len(rs))
	for i, r := range rs {
		sep := ","
		if i == len(rs)-1 {
			sep = ""
		}
		fmt.Fprintf(w, "    {0x%XUL, 0x%XUL}%s\n", r.lo, r.hi, sep)
	}
	fmt.Fprintf(w, "};\n\n")
}

func main() {
	w := os.Stdout
	fmt.Fprintf(w, "/* Generated by tools/gen_unicode (%s, Unicode %s). Do not edit. */\n", runtime.Version(), unicode.Version)
	fmt.Fprintf(w, "#include \"mark_unicode.h\"\n\n")
	fmt.Fprintf(w, "typedef struct MarkRange {\n    unsigned long lo, hi;\n} MarkRange;\n\n")
	fmt.Fprintf(w, "typedef struct MarkLower {\n    unsigned long from, to;\n} MarkLower;\n\n")
	table(w, "punct", "unicode.IsPunct (category P)", ranges(unicode.IsPunct))
	table(w, "space", "unicode.IsSpace", ranges(unicode.IsSpace))
	table(w, "letter", "unicode.IsLetter (category L)", ranges(unicode.IsLetter))
	table(w, "digit", "unicode.IsDigit (category Nd)", ranges(unicode.IsDigit))
	var lower []MarkLower
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if l := unicode.ToLower(r); l != r {
			lower = append(lower, MarkLower{r, l})
		}
	}
	fmt.Fprintf(w, "/* unicode.ToLower, for every code point it changes. */\nstatic const MarkLower lower[%d] = {\n", len(lower))
	for i, p := range lower {
		sep := ","
		if i == len(lower)-1 {
			sep = ""
		}
		fmt.Fprintf(w, "    {0x%XUL, 0x%XUL}%s\n", p.from, p.to, sep)
	}
	fmt.Fprintf(w, "};\n\n")
	fmt.Fprint(w, functions)
}

type MarkLower struct{ from, to rune }

const functions = `static int in_ranges(const MarkRange *t, size_t n, unsigned long c)
{
    size_t lo = 0, hi = n;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        if (c < t[mid].lo) {
            hi = mid;
        } else if (c > t[mid].hi) {
            lo = mid + 1;
        } else {
            return 1;
        }
    }
    return 0;
}

int mark_is_punct(unsigned long c)
{
    return in_ranges(punct, sizeof punct / sizeof punct[0], c);
}

int mark_is_space(unsigned long c)
{
    return in_ranges(space, sizeof space / sizeof space[0], c);
}

int mark_is_letter(unsigned long c)
{
    return in_ranges(letter, sizeof letter / sizeof letter[0], c);
}

int mark_is_digit(unsigned long c)
{
    return in_ranges(digit, sizeof digit / sizeof digit[0], c);
}

unsigned long mark_to_lower(unsigned long c)
{
    size_t lo = 0, hi = sizeof lower / sizeof lower[0];
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        if (c < lower[mid].from) {
            hi = mid;
        } else if (c > lower[mid].from) {
            lo = mid + 1;
        } else {
            return lower[mid].to;
        }
    }
    return c;
}
`
