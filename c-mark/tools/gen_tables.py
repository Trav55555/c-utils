#!/usr/bin/env python3
"""Generate c-mark's two data tables from goldmark's Go sources.

    python3 tools/gen_tables.py path/to/goldmark-v1.6.0 src

reads util/html5entities.go and util/unicode_case_folding.go under the
first argument and writes src/mark_entities.c and src/mark_casefold.c
under the second. Python 3 standard library only. The tables are sorted so
the C side can binary-search them; the Go side uses maps, so the order
there carries no meaning.
"""
import os
import re
import sys

ENTITY_RE = re.compile(
    r'^\s*"(?P<key>[A-Za-z0-9]+)":\s*\{Name:\s*"(?P<name>[A-Za-z0-9]+)",'
    r'\s*CodePoints:\s*\[\]int\{(?P<cps>[0-9, ]*)\},'
    r'\s*Characters:\s*\[\]byte\{(?P<bytes>[0-9a-fx, ]*)\}\},\s*$')

FOLD_RE = re.compile(
    r'^\s*0x(?P<from>[0-9a-fA-F]+):\s*\[\]int32\{(?P<to>[0-9, ]+)\},\s*$')


def c_bytes(values):
    """A C string literal of the given byte values, every byte escaped so
    the literal never runs a hex escape into a following digit."""
    return '"' + ''.join('\\x%02x' % b for b in values) + '"'


def read_entities(path):
    entities = []
    with open(path, encoding='utf-8') as f:
        for line in f:
            m = ENTITY_RE.match(line)
            if m is None:
                continue
            if m.group('key') != m.group('name'):
                raise SystemExit('entity key/name mismatch: ' + line.strip())
            raw = [int(b, 16) for b in m.group('bytes').split(',') if b.strip()]
            entities.append((m.group('name'), raw))
    if len(entities) < 2000:
        raise SystemExit('only %d entities parsed from %s' % (len(entities), path))
    # Sort by bytewise name order, which is what the C lookup compares.
    entities.sort(key=lambda e: e[0].encode('ascii'))
    return entities


def read_foldings(path):
    folds = []
    with open(path, encoding='utf-8') as f:
        for line in f:
            m = FOLD_RE.match(line)
            if m is None:
                continue
            to = [int(x) for x in m.group('to').split(',') if x.strip()]
            if not 1 <= len(to) <= 3:
                raise SystemExit('unexpected folding width: ' + line.strip())
            folds.append((int(m.group('from'), 16), to))
    if len(folds) < 1000:
        raise SystemExit('only %d foldings parsed from %s' % (len(folds), path))
    folds.sort(key=lambda e: e[0])
    return folds


def write_entities(entities, out_path, rel_src):
    with open(out_path, 'w', encoding='ascii') as f:
        f.write('/* Generated by tools/gen_tables.py from %s\n' % rel_src)
        f.write(' * (goldmark v1.6.0, util.LookUpHTML5EntityByName). Do not edit;\n')
        f.write(' * regenerate with: python3 tools/gen_tables.py REF src */\n')
        f.write('#include "mark_util.h"\n\n')
        f.write('#define MARK_ENTITY_COUNT %d\n\n' % len(entities))
        f.write('/* Sorted by name in byte order for the binary search below. */\n')
        f.write('static const MarkEntity entities[MARK_ENTITY_COUNT] = {\n')
        for name, raw in entities:
            f.write('    {"%s", %d, %s, %d},\n' % (name, len(name), c_bytes(raw), len(raw)))
        f.write('};\n\n')
        f.write('/* util.LookUpHTML5EntityByName */\n')
        f.write('const MarkEntity *mark_entity_lookup(CuStr name)\n')
        f.write('{\n')
        f.write('    size_t lo = 0;\n')
        f.write('    size_t hi = MARK_ENTITY_COUNT;\n\n')
        f.write('    while (lo < hi) {\n')
        f.write('        size_t mid = lo + (hi - lo) / 2;\n')
        f.write('        const MarkEntity *e = &entities[mid];\n')
        f.write('        size_t n = name.len < e->name_len ? name.len : e->name_len;\n')
        f.write('        int c = memcmp(name.ptr, e->name, n);\n\n')
        f.write('        if (c == 0) {\n')
        f.write('            if (name.len == e->name_len) return e;\n')
        f.write('            c = name.len < e->name_len ? -1 : 1;\n')
        f.write('        }\n')
        f.write('        if (c < 0) hi = mid;\n')
        f.write('        else lo = mid + 1;\n')
        f.write('    }\n')
        f.write('    return NULL;\n')
        f.write('}\n')


def write_foldings(folds, out_path, rel_src):
    with open(out_path, 'w', encoding='ascii') as f:
        f.write('/* Generated by tools/gen_tables.py from %s\n' % rel_src)
        f.write(' * (goldmark v1.6.0, util.unicodeCaseFoldings). Do not edit;\n')
        f.write(' * regenerate with: python3 tools/gen_tables.py REF src */\n')
        f.write('#include "mark_util.h"\n\n')
        f.write('#define MARK_FOLD_COUNT %d\n\n' % len(folds))
        f.write('/* Sorted by code point for the binary search below. */\n')
        f.write('static const MarkFolding foldings[MARK_FOLD_COUNT] = {\n')
        for src, to in folds:
            padded = to + [0] * (3 - len(to))
            f.write('    {0x%XUL, {%s}, %d},\n' % (src, ', '.join('0x%XUL' % x for x in padded), len(to)))
        f.write('};\n\n')
        f.write('/* The entry for code point c in util.unicodeCaseFoldings, or NULL. */\n')
        f.write('const MarkFolding *mark_folding_lookup(unsigned long c)\n')
        f.write('{\n')
        f.write('    size_t lo = 0;\n')
        f.write('    size_t hi = MARK_FOLD_COUNT;\n\n')
        f.write('    while (lo < hi) {\n')
        f.write('        size_t mid = lo + (hi - lo) / 2;\n\n')
        f.write('        if (foldings[mid].from == c) return &foldings[mid];\n')
        f.write('        if (foldings[mid].from < c) lo = mid + 1;\n')
        f.write('        else hi = mid;\n')
        f.write('    }\n')
        f.write('    return NULL;\n')
        f.write('}\n')


def main(argv):
    if len(argv) != 3:
        raise SystemExit(__doc__)
    ref, out = argv[1], argv[2]
    ent_src = os.path.join(ref, 'util', 'html5entities.go')
    fold_src = os.path.join(ref, 'util', 'unicode_case_folding.go')
    write_entities(read_entities(ent_src), os.path.join(out, 'mark_entities.c'), 'util/html5entities.go')
    write_foldings(read_foldings(fold_src), os.path.join(out, 'mark_casefold.c'), 'util/unicode_case_folding.go')


if __name__ == '__main__':
    main(sys.argv)
